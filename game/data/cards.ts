export const CARD_BY_SLUG = new Map(CARDS.map((c) => [c.slug, c]));

export function getCard(slug: string): CardDef {
  const c = CARD_BY_SLUG.get(slug);
  if (!c) throw new Error(`Unknown card ${slug}`);
  return c;
}

/** Find by slug or (case-insensitive) name prefix — what players type. */
export function findCard(query: string): CardDef | undefined {
  const q = query.trim().toLowerCase();
  return CARD_BY_SLUG.get(q) ?? CARDS.find((c) => c.name.toLowerCase() === q) ?? CARDS.find((c) => c.name.toLowerCase().startsWith(q));
}

